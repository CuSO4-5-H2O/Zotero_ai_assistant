class ManualLibrary:
    def __init__(self,root:Path,render):
        self.root=Path(root).resolve();self.render=render;self._lock=threading.RLock()
        self._stamp=None;self._data={};self._sources={};self._aliases={};self._chapters={};self._cases={}
        self._text_cache={}

    def _path(self,name,suffix=None):
        if not isinstance(name,str) or not name or '\\' in name or ':' in name:
            raise ValueError('无效手册资源')
        file=(self.root/name).resolve()
        if not file.is_relative_to(self.root) or (suffix and file.suffix!=suffix):
            raise ValueError('无效手册资源')
        return file

    def _reload(self):
        with self._lock:
            manifest=self.root/'manifest.json';catalog=self.root/'evidence/sources.json'
            stamp=tuple((p.stat().st_mtime_ns,p.stat().st_size) for p in (manifest,catalog))
            if stamp==self._stamp:return
            doc=read_json(manifest);sources=read_json(catalog)
            chapters={};cases={};aliases={};lookup={}
            for entry in doc['chapters']:
                cid=entry.get('id','')
                if not ID_RE.fullmatch(cid) or cid in chapters:raise ValueError('手册章节编号冲突')
                self._path(entry['file'],'.md');chapters[cid]=entry
            for item in sources:
                if item.get('reader_render_version')!=READER_RENDER_VERSION or not isinstance(item.get('reader_markdown'),str):
                    item['reader_markdown']=reader_source_markdown(item.get('card_markdown',''))
                sid=item.get('id','')
                if not ID_RE.fullmatch(sid) or sid in lookup:raise ValueError('手册来源编号冲突')
                lookup[sid]=item
                for key in [sid,*item.get('aliases',[])]:
                    if key in aliases and aliases[key]!=sid:raise ValueError('手册来源别名冲突')
                    aliases[key]=sid
            for item in doc.get('cases',[]):
                cid=item.get('id','')
                if not ID_RE.fullmatch(cid) or cid in cases:raise ValueError('手册案例编号冲突')
                self._path(item['file'],'.md');cases[cid]=item
            self._data=doc;self._sources=lookup;self._aliases=aliases
            self._chapters=chapters;self._cases=cases;self._text_cache={};self._stamp=stamp

    @staticmethod
    def _source_summary(item):
        return {k:v for k,v in item.items() if k not in {'card_markdown','reader_markdown','reader_render_version','source_path','pdf_path','card_path'}}

    def _text(self,entry):
        file=self._path(entry['file'],'.md');stamp=(file.stat().st_mtime_ns,file.stat().st_size)
        cached=self._text_cache.get(entry['file'])
        if cached and cached[0]==stamp:return cached[1]
        content=file.read_text('utf-8-sig');self._text_cache[entry['file']]=(stamp,content);return content

    def info(self):
        self._reload()
        return {**{k:v for k,v in self._data.items() if k not in {'source_manifest','cases'}},
                'sources':[self._source_summary(s) for s in self._sources.values()],
                'cases':list(self._cases.values())}

    def _render(self,content):
        parser=EvidenceLinks(self._aliases);parser.feed(self.render(content));parser.close()
        return ''.join(parser.parts)

    def chapter(self,cid):
        self._reload()
        if cid not in self._chapters:raise FileNotFoundError('没有该手册章节')
        item=self._chapters[cid];content=self._text(item)
        return {**item,'markdown':content,'html':self._render(content),'sha256':digest(content)}

    def source(self,sid):
        if not isinstance(sid,str) or not ID_RE.fullmatch(sid):raise ValueError('无效的文献编号')
        self._reload();canonical=self._aliases.get(sid)
        if not canonical:raise FileNotFoundError('该来源尚未收录手册')
        item=self._sources[canonical]
        content=item['reader_markdown']
        return {**self._source_summary(item),'card_markdown':content,
                'card_html':self._render(content)}

    def case(self,cid):
        self._reload()
        if cid not in self._cases:raise FileNotFoundError('没有该手册案例')
        item=self._cases[cid];content=self._text(item)
        return {**item,'markdown':content,'html':self._render(content),'sha256':digest(content)}

    @staticmethod
    def _score(query,text,title=''):
        words=query.casefold().split();text=text.casefold();title=title.casefold()
        if not all(w in text for w in words):return 0
        return 1+sum(5 for w in words if w in title)+sum(min(5,text.count(w)) for w in words)

    @staticmethod
    def _snippet(query,text):
        stripped=re.sub(r'\s+',' ',re.sub(r'[#*`|>\[\]]',' ',text))
        positions=[stripped.casefold().find(w) for w in query.casefold().split()]
        start=max(0,min((p for p in positions if p>=0),default=0)-45)
        return ('…' if start else '')+stripped[start:start+180]

    def search(self,query):
        self._reload()
        if not isinstance(query,str) or len(query)>250:raise ValueError('搜索词限250字')
        query=query.strip();result={'query':query,'chapters':[],'sources':[],'cases':[]}
        if not query:return result
        for kind,items in (('chapters',self._chapters),('cases',self._cases)):
            matches=[]
            for item in items.values():
                body=self._text(item);text=' '.join([item['id'],item['title'],*item.get('tags',[]),body])
                score=self._score(query,text,item['title'])
                if score:matches.append((score,{**item,'snippet':self._snippet(query,body)}))
            result[kind]=[v for _,v in sorted(matches,key=lambda x:(-x[0],x[1]['id']))[:50]]
        matches=[]
        for item in self._sources.values():
            body=item['reader_markdown'];text=' '.join([item['id'],item['title'],item.get('doi',''),*item.get('tags',[]),body])
            score=self._score(query,text,item['title'])
            if score:matches.append((score,{**self._source_summary(item),'snippet':self._snippet(query,body)}))
        result['sources']=[v for _,v in sorted(matches,key=lambda x:(-x[0],x[1]['id']))[:80]]
        return result

    def pdf_request(self,sid,page=None):
        item=self.source(sid);z=item.get('zotero',{})
        if not item.get('has_pdf') or not re.fullmatch('[A-Z0-9]{8}',z.get('attachment_key','')):
            raise ValueError('该来源没有已核验的Zotero PDF链接')
        if page is not None and (isinstance(page,bool) or not isinstance(page,int) or not 1<=page<=100000):
            raise ValueError('PDF页码须为正整数')
        return {'action':'open_pdf','paper_id':item['id'],'page':page,**z}

    def export(self):
        self._reload();stream=io.BytesIO()
        # Explicit generated manifest only: never include personal notes, PDFs,
        # runtime credentials, worklogs, or arbitrary paths supplied by a client.
        names={'manifest.json','evidence/sources.json','README.md','handbook.md'}
        names.update(x['file'] for x in self._chapters.values())
        names.update(x['file'] for x in self._cases.values())
        with zipfile.ZipFile(stream,'w',zipfile.ZIP_DEFLATED) as archive:
            for name in sorted(names):
                file=self._path(name)
                if file.is_file():archive.writestr(name,file.read_bytes())
        return stream.getvalue()
